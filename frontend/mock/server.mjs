// ---- helpers ---------------------------------------------------------------
const CROCKFORD = '0123456789ABCDEFGHJKMNPQRSTVWXYZ';
function ulid(ms = Date.now()) {
  let t = '';
  for (let i = 0; i < 10; i++) { t = CROCKFORD[ms % 32] + t; ms = Math.floor(ms / 32); }
  const rnd = randomBytes(16);
  let r = '';
  for (let i = 0; i < 16; i++) r += CROCKFORD[rnd[i] % 32];
  return t + r;
}
const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');
const iso = (ms) => new Date(ms).toISOString();
const rand = (a, b) => Math.round(a + Math.random() * (b - a));
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const countPages = (buf) => Math.max(1, (buf.toString('latin1').match(/\/Type\s*\/Page(?![s\w])/g) || []).length);

const sampleFileCache = new Map();
function sampleFile(sample) {
  if (sampleFileCache.has(sample.id)) return sampleFileCache.get(sample.id);
  const real = path.join(DATA_DIR, sample.file);
  let buf;
  let placeholder = false;
  if (existsSync(real)) buf = readFileSync(real);
  else {
    placeholder = true;
    const c = CANNED[sample.id];
    buf = buildPdf({
      heading: c.extraction.vendor_name.value,
      lines: printedLines(sample.id).slice(1),
      footer: `Placeholder preview generated by frontend/mock for sample ${sample.id}. The real fixture PDFs live in data/samples/.`,
      scanned: c.document_class === 'scanned',
    });
  }
  const entry = { buf, hash: sha256(buf), pages: countPages(buf), name: path.basename(sample.file), placeholder };
  sampleFileCache.set(sample.id, entry);
  return entry;
}

function blankStage(def, i) {
  return { key: def.key, index: i + 1, name: def.name, status: 'pending', started_at: null, finished_at: null, duration_ms: null, summary: '', warnings: [], output: null };
}

const SUMMARY_KEYS = ['id', 'created_at', 'filename', 'sample_id', 'file_hash', 'status', 'document_class', 'decision', 'confidence', 'vendor_name', 'vendor_id', 'invoice_number', 'invoice_date', 'currency', 'net_total', 'gross_total', 'po_number', 'duration_ms', 'current_stage', 'error'];
const summaryOf = (run) => Object.fromEntries(SUMMARY_KEYS.map((k) => [k, run[k] ?? null]));
const detailOf = (run) => ({ ...summaryOf(run), stages: run.stages.map((s) => ({ ...s })) });

function newRun({ filename, sampleId, buf, createdMs = Date.now() }) {
  const run = {
    id: `run_${ulid(createdMs)}`, created_at: iso(createdMs), filename, sample_id: sampleId, file_hash: sha256(buf),
    status: 'queued', document_class: null, decision: null, confidence: null, vendor_name: null, vendor_id: null,
    invoice_number: null, invoice_date: null, currency: null, net_total: null, gross_total: null, po_number: null,
    duration_ms: null, current_stage: null, error: null,
    stages: STAGE_DEFS.map(blankStage), events: [], subs: new Set(), file: buf, terminal: false,
  };
  runs.set(run.id, run);
  return run;
}

// ---- event emission --------------------------------------------------------
function emit(run, type, data, ts) {
  const ev = { seq: run.events.length + 1, type, data, ts };
  run.events.push(ev);
  const frame = sseFrame(ev);
  for (const res of run.subs) res.write(frame);
  if (type === 'run.completed' || type === 'run.failed') {
    run.terminal = true;
    for (const res of run.subs) res.end();
    run.subs.clear();
  }
}
const sseFrame = (ev) => `id: ${ev.seq}\nevent: ${ev.type}\ndata: ${JSON.stringify(ev.data)}\n\n`;

// ---- pipeline execution ----------------------------------------------------
function delayFor(key, run) {
  if (key === 'extraction') return run.useCache ? rand(500, 800) : run.document_class_hint === 'scanned' ? rand(6000, 7000) : rand(4000, 6200);
  if (key === 'decision') return rand(300, 450);
  return rand(300, 800);
}

/** Build the stage plan for a run: sample-backed, or a generic upload that fails. */
function planFor(run) {
  const size = run.file.length;
  const isPdf = run.file.subarray(0, 5).toString('latin1') === '%PDF-';
  const pageCount = isPdf ? countPages(run.file) : 0;
  if (!isPdf || size > MAX_BYTES) {
    const why = !isPdf ? 'File is not a PDF (missing %PDF header).' : `File is ${(size / 1048576).toFixed(1)} MB; the limit is 15 MB.`;
    return { failAt: 0, error: why, stages: [{ key: 'intake', output: { filename: run.filename, size_bytes: size, sha256: run.file_hash, page_count: 0, sample_id: null }, summary: `Rejected at intake. ${why}`, warnings: [] }] };
  }
  if (run.sample_id) {
    run.document_class_hint = CANNED[run.sample_id].document_class;
    return computeRun({ sampleId: run.sample_id, filename: run.filename, size, sha256: run.file_hash, pageCount, ledger, useCache: run.useCache });
  }
  const text = run.file.toString('latin1');
  const hasFont = /\/Font/.test(text);
  const chars = hasFont ? Math.min(4000, Math.round(size / 12)) : 0;
  const pages = Array.from({ length: pageCount }, (_, i) => ({ page: i + 1, chars: hasFont ? Math.round(chars / pageCount) : 0, has_text_layer: hasFont }));
  const cls = hasFont ? 'digital' : 'scanned';
  run.document_class_hint = cls;
  const error = 'The mock server can only extract the eight sample invoices. Drop one of the files from data/samples/ or pick a sample on the left.';
  return {
    failAt: 2, error,
    stages: [
      { key: 'intake', output: { filename: run.filename, size_bytes: size, sha256: run.file_hash, page_count: pageCount, sample_id: null }, summary: `Received ${run.filename} (${(size / 1024).toFixed(1)} KB, ${pageCount} page${pageCount > 1 ? 's' : ''}).`, warnings: [] },
      { key: 'doc_analysis', output: { document_class: cls, pages, text_layer: '', language_guess: 'en' }, summary: cls === 'scanned' ? `${pageCount} page${pageCount > 1 ? 's' : ''}, no text layer — using vision extraction.` : `${pageCount} page${pageCount > 1 ? 's' : ''}, text layer present.`, warnings: [] },
      { key: 'extraction', output: null, summary: 'Extraction failed: unrecognised document in mock mode.', warnings: [] },
    ],
  };
}

/** Runs the pipeline. `clock` abstracts time so history seeding can run instantly. */
async function execute(run, clock) {
  const t0 = clock.now();
  run.status = 'running';
  const plan = planFor(run);
  emit(run, 'run.started', { run_id: run.id, created_at: run.created_at, filename: run.filename, sample_id: run.sample_id }, iso(t0));

  for (let i = 0; i < STAGE_DEFS.length; i++) {
    const rec = run.stages[i];
    const step = plan.stages[i];
    const start = clock.now();
    Object.assign(rec, { status: 'running', started_at: iso(start) });
    run.current_stage = rec.key;
    if (rec.key === 'doc_analysis' && step) run.document_class = null;
    emit(run, 'stage.started', { run_id: run.id, stage: { ...rec } }, iso(start));
    await clock.wait(Math.round(delayFor(rec.key, run) * SPEED));
    const end = clock.now();
    const timing = { started_at: iso(start), finished_at: iso(end), duration_ms: end - start };

    if (plan.failAt === i) {
      Object.assign(rec, timing, { status: 'failed', summary: step.summary, warnings: step.warnings, output: step.output });
      emit(run, 'stage.failed', { run_id: run.id, stage: { ...rec }, error: plan.error }, iso(end));
      for (let j = i + 1; j < run.stages.length; j++) Object.assign(run.stages[j], { status: 'skipped', summary: 'Skipped because an earlier stage failed.' });
      Object.assign(run, { status: 'failed', error: plan.error, duration_ms: end - t0 });
      if (i >= 1) run.document_class = plan.stages[1]?.output?.document_class ?? null;
      emit(run, 'run.failed', { run_id: run.id, error: plan.error, summary: summaryOf(run) }, iso(end));
      return;
    }

    const output = structuredClone(step.output);
    if (rec.key === 'extraction') output.latency_ms = timing.duration_ms;
    Object.assign(rec, timing, { status: step.status ?? 'done', summary: step.summary, warnings: step.warnings, output });
    if (rec.key === 'doc_analysis') run.document_class = output.document_class;
    emit(run, 'stage.completed', { run_id: run.id, stage: { ...rec } }, iso(end));
  }

  const end = clock.now();
  Object.assign(run, plan.run, { status: 'completed', duration_ms: end - t0, current_stage: 'decision' });
  if (plan.ledgerRow && !clock.virtual) ledger.push({ id: ++ledgerSeq, ...plan.ledgerRow, processed_at: iso(end), source: 'run', run_id: run.id });
  emit(run, 'run.completed', { run_id: run.id, summary: summaryOf(run), decision: plan.decision }, iso(end));
}

const realClock = { virtual: false, now: () => Date.now(), wait: sleep };
function virtualClock(startMs) {
  let t = startMs;
  return { virtual: true, now: () => t, wait: async (ms) => { t += ms; } };
}

function startRun(run) {
  queue = queue.then(() => execute(run, realClock)).catch((err) => {
    console.error('[mock] run crashed', run.id, err);
    Object.assign(run, { status: 'failed', error: String(err?.message || err) });
    if (!run.terminal) emit(run, 'run.failed', { run_id: run.id, error: run.error, summary: summaryOf(run) }, iso(Date.now()));
  });
}

async function seedHistory() {
  const H = 3600000;
  const now = Date.now();
  const plan = [
    { id: 'EC1', ago: 27 * H },
    { id: 'EC3', ago: 6.5 * H },
    { id: null, ago: 5 * H, filename: 'vendor_scan_IMG_2231.jpg' },
    { id: 'EC6', ago: 3.2 * H },
    { id: 'EC4', ago: 2.1 * H },
  ];
  for (const p of plan) {
    const created = now - p.ago;
    let run;
    if (p.id) {
      const s = SAMPLES.find((x) => x.id === p.id);
      const f = sampleFile(s);
      run = newRun({ filename: f.name, sampleId: s.id, buf: f.buf, createdMs: created });
    } else {
      run = newRun({ filename: p.filename, sampleId: null, buf: Buffer.from('\xff\xd8\xff\xe0 not a pdf', 'latin1'), createdMs: created });
    }
    await execute(run, virtualClock(created + 120));
  }
}

// ---- HTTP plumbing ----------------------------------------------------------
const CORS = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Methods': 'GET,POST,OPTIONS',
  'Access-Control-Allow-Headers': 'Content-Type, Last-Event-ID',
};
function send(res, status, body, headers = {}) {
  const isBuf = Buffer.isBuffer(body);
  res.writeHead(status, { ...CORS, 'Content-Type': isBuf ? 'application/octet-stream' : 'application/json; charset=utf-8', ...headers });
  res.end(isBuf ? body : JSON.stringify(body));
}
const sendError = (res, status, code, message) => send(res, status, { error: { code, message } });

function readBody(req, limit = 20 * 1024 * 1024) {
  return new Promise((resolve, reject) => {
    const chunks = [];
    let n = 0;
    req.on('data', (c) => {
      n += c.length;
      if (n > limit) { reject(Object.assign(new Error('Body too large'), { status: 413 })); req.destroy(); return; }
      chunks.push(c);
    });
    req.on('end', () => resolve(Buffer.concat(chunks)));
    req.on('error', reject);
  });
}

function parseMultipart(buf, contentType) {
  const m = /boundary=(?:"([^"]+)"|([^;]+))/i.exec(contentType || '');
  if (!m) return null;
  const boundary = Buffer.from(`--${m[1] || m[2]}`);
  const parts = {};
  let pos = buf.indexOf(boundary);
  while (pos !== -1) {
    const start = pos + boundary.length;
    if (buf.subarray(start, start + 2).toString() === '--') break;
    const next = buf.indexOf(boundary, start);
    if (next === -1) break;
    const part = buf.subarray(start + 2, next - 2); // strip leading CRLF and trailing CRLF
    const sep = part.indexOf('\r\n\r\n');
    if (sep !== -1) {
      const head = part.subarray(0, sep).toString('utf8');
      const name = /name="([^"]*)"/i.exec(head)?.[1];
      const filename = /filename="([^"]*)"/i.exec(head)?.[1];
      if (name) parts[name] = { filename, data: part.subarray(sep + 4) };
    }
    pos = next;
  }
  return parts;
}

function sampleForUpload(filename, buf) {
  const h = sha256(buf);
  const base = path.basename(filename || '').toLowerCase();
  for (const s of SAMPLES) {
    const f = sampleFile(s);
    if (f.hash === h || f.name.toLowerCase() === base || base.startsWith(`${s.id.toLowerCase()}_`)) return s.id;
  }
  return null;
}

function stats() {
  const all = [...runs.values()];
  const done = all.filter((r) => r.status === 'completed');
  const count = (d) => done.filter((r) => r.decision === d).length;
  const durs = all.filter((r) => r.duration_ms != null && r.status !== 'running').map((r) => r.duration_ms).sort((a, b) => a - b);
  const median = durs.length ? (durs.length % 2 ? durs[(durs.length - 1) / 2] : Math.round((durs[durs.length / 2 - 1] + durs[durs.length / 2]) / 2)) : 0;
  const approve = count('APPROVE');
  return {
    runs: all.length, approve, hold: count('HOLD'), reject: count('REJECT'),
    auto_approval_rate: done.length ? r2(approve / done.length) : 0,
    median_duration_ms: median,
    last_24h: all.filter((r) => Date.now() - Date.parse(r.created_at) < 86400000).length,
  };
}

function referencePos() {
  return POS.map((p) => {
    const rows = ledger.filter((r) => r.po_number === p.po_number);
    const billed = r2(rows.filter((r) => r.decision === 'APPROVE').reduce((s, r) => s + r.net_total, 0));
    return { ...p, lines: p.lines.map((l) => ({ ...l })), billed_net_to_date: billed, remaining_net: r2(p.net_total - billed), invoices: rows.map((r) => ({ invoice_number: r.invoice_number, net_total: r.net_total, decision: r.decision, source: r.source })) };
  });
}

// ---- routes -----------------------------------------------------------------
async function handle(req, res) {
  const url = new URL(req.url, `http://${req.headers.host || 'localhost'}`);
  const p = url.pathname.replace(/\/+$/, '') || '/';
  const method = req.method;
  if (method === 'OPTIONS') { res.writeHead(204, CORS); res.end(); return; }

  if (method === 'GET' && p === '/health') return send(res, 200, { ok: true, model: MODEL, db: 'ok', mock: true });

  if (method === 'GET' && p === '/api/samples') {
    const items = [...SAMPLES].sort((a, b) => a.demo_order - b.demo_order).map((s) => ({ ...s, url: `/api/samples/${s.id}/file` }));
    return send(res, 200, items);
  }
  let m = /^\/api\/samples\/([^/]+)\/file$/.exec(p);
  if (method === 'GET' && m) {
    const s = SAMPLES.find((x) => x.id === decodeURIComponent(m[1]));
    if (!s) return sendError(res, 404, 'sample_not_found', `No sample ${m[1]}`);
    const f = sampleFile(s);
    return send(res, 200, f.buf, { 'Content-Type': 'application/pdf', 'Content-Disposition': `inline; filename="${f.name}"` });
  }

  if (p === '/api/runs' && method === 'POST') {
    const body = await readBody(req);
    const ct = req.headers['content-type'] || '';
    let run;
    if (ct.includes('multipart/form-data')) {
      const parts = parseMultipart(body, ct);
      const file = parts?.file;
      if (!file || !file.data?.length) return sendError(res, 400, 'missing_file', 'Multipart body must contain a non-empty "file" field.');
      const filename = file.filename || 'upload.pdf';
      run = newRun({ filename, sampleId: sampleForUpload(filename, file.data), buf: Buffer.from(file.data) });
    } else {
      let json;
      try { json = JSON.parse(body.toString('utf8') || '{}'); } catch { return sendError(res, 400, 'bad_json', 'Body is not valid JSON.'); }
      const s = SAMPLES.find((x) => x.id === json.sample_id);
      if (!s) return sendError(res, json.sample_id ? 404 : 400, json.sample_id ? 'sample_not_found' : 'missing_input', json.sample_id ? `No sample ${json.sample_id}` : 'Send multipart "file" or JSON { "sample_id" }.');
      const f = sampleFile(s);
      run = newRun({ filename: f.name, sampleId: s.id, buf: f.buf });
      run.useCache = !!json.use_cache;
    }
    startRun(run);
    return send(res, 202, { run_id: run.id });
  }

  if (p === '/api/runs' && method === 'GET') {
    const limit = Math.min(200, Math.max(1, Number(url.searchParams.get('limit')) || 50));
    const offset = Math.max(0, Number(url.searchParams.get('offset')) || 0);
    const decision = (url.searchParams.get('decision') || '').toUpperCase();
    const q = (url.searchParams.get('q') || '').trim().toLowerCase();
    let items = [...runs.values()].sort((a, b) => b.created_at.localeCompare(a.created_at));
    if (decision) items = items.filter((r) => r.decision === decision);
    if (q) items = items.filter((r) => [r.filename, r.vendor_name, r.invoice_number, r.po_number, r.sample_id, r.id].some((v) => v && String(v).toLowerCase().includes(q)));
    return send(res, 200, { items: items.slice(offset, offset + limit).map(summaryOf), total: items.length });
  }

  m = /^\/api\/runs\/([^/]+)(\/events|\/file)?$/.exec(p);
  if (method === 'GET' && m) {
    const run = runs.get(decodeURIComponent(m[1]));
    if (!run) return sendError(res, 404, 'run_not_found', `No run ${m[1]}`);
    if (!m[2]) return send(res, 200, detailOf(run));
    if (m[2] === '/file') {
      const isPdf = run.file.subarray(0, 5).toString('latin1') === '%PDF-';
      return send(res, 200, run.file, { 'Content-Type': isPdf ? 'application/pdf' : 'application/octet-stream', 'Content-Disposition': `inline; filename="${run.filename.replace(/"/g, '')}"` });
    }
    // SSE: replay everything, then stream live, close after the terminal event.
    res.writeHead(200, { ...CORS, 'Content-Type': 'text/event-stream; charset=utf-8', 'Cache-Control': 'no-cache, no-transform', Connection: 'keep-alive', 'X-Accel-Buffering': 'no' });
    res.write('retry: 1500\n\n');
    for (const ev of run.events) res.write(sseFrame(ev));
    if (run.terminal) { res.end(); return; }
    run.subs.add(res);
    const ping = setInterval(() => res.write(': ping\n\n'), 15000);
    // end() rather than destroy(): an abrupt destroy is not propagated by the Vite dev proxy, so the
    // browser would only notice via its stall watchdog. end() exercises the fast reconnect path.
    const drop = SSE_DROP ? setTimeout(() => { console.log('[mock] dropping SSE connection for', run.id); run.subs.delete(res); res.end(); }, 2500) : null;
    req.on('close', () => { clearInterval(ping); if (drop) clearTimeout(drop); run.subs.delete(res); });
    return;
  }

  if (method === 'GET' && p === '/api/stats') return send(res, 200, stats());
  if (method === 'GET' && p === '/api/reference/vendors') return send(res, 200, VENDORS);
  if (method === 'GET' && p === '/api/reference/pos') return send(res, 200, referencePos());
  if (method === 'GET' && p === '/api/reference/ledger') return send(res, 200, [...ledger].sort((a, b) => b.processed_at.localeCompare(a.processed_at)));

  if (method === 'POST' && p === '/api/admin/reset') {
    let json = {};
    try { json = JSON.parse((await readBody(req)).toString('utf8') || '{}'); } catch { /* default */ }
    ledger = freshLedger();
    if (json.clear_runs) for (const [id, r] of runs) if (r.terminal) runs.delete(id);
    return send(res, 200, { ok: true });
  }

  return sendError(res, 404, 'not_found', `${method} ${p} is not a mock endpoint`);
}

const server = http.createServer((req, res) => {
  handle(req, res).catch((err) => {
    console.error('[mock]', err);
    if (!res.headersSent) sendError(res, err.status || 500, 'internal', String(err.message || err));
    else res.end();
  });
});

if (SEED_HISTORY) await seedHistory();
server.listen(PORT, () => {
  const real = SAMPLES.filter((s) => !sampleFile(s).placeholder).length;
  console.log(`[mock] API + SSE on http://localhost:${PORT}  (speed x${1 / SPEED}${SSE_DROP ? ', SSE drop on' : ''})`);
  console.log(`[mock] ${SAMPLES.length} samples (${real} real PDFs from data/samples, ${SAMPLES.length - real} placeholders), ${runs.size} seeded runs, ledger ${ledger.length} rows`);
});
