// Mock API + SSE server for frontend development (docs/SPEC.md §5, §6, §8).
// Node built-ins only. Start with `npm run mock` (port 8000).
//
// Env knobs:
//   PORT=8000             listen port
//   MOCK_FAST=1           divide all stage delays by 5 (quick iteration)
//   MOCK_SSE_DROP=1       drop every live SSE connection after ~2.5 s (tests client reconnect)
//   MOCK_HISTORY=0        start with an empty run history (default seeds a few past runs)
// Equivalent flags: --fast, --drop, --no-history  (e.g. `npm run mock -- --drop`)

